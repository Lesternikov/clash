def main():
    try:
        # Konwertujemy z zachowaniem Al)pha
        img = pygame.image.load(PLIK_ZRODLOWY).convert_alpha()
    except Exception as e:
        print(f"Nie udało się załadować {PLIK_ZRODLOWY}: {e}")
        return

    # ============================================================
    # 2. LICZENIE UNIKALNYCH KOLORÓW
    # ============================================================
    unique_colors = set()
    for x in range(img.get_width()):
        for y in range(img.get_height()):
            unique_colors.add(tuple(img.get_at((x, y))))
            
    print("-" * 50)
    print(f"ANALIZA PLIKU: {PLIK_ZRODLOWY}")
    print(f"Komputer znalazł dokładnie: {len(unique_colors)} unikalnych kolorów!")
    print("-" * 50)

    # ============================================================
    # 3. NIEZAWODNA PODMIANA KOLORÓW (RGB)
    # ============================================================
    new_img = img.copy()

    # Tłumaczymy COLOR_MAP na czyste RGB (ignorujemy czwartą wartość Alpha)
    paleta_rgb = {}
    for old_color, new_color in COLOR_MAP.items():
        paleta_rgb[old_color[:3]] = new_color

    # Skanujemy piksel po pikselu
    for x in range(new_img.get_width()):
        for y in range(new_img.get_height()):
            kolor_piksela = new_img.get_at((x, y))
            
            # Pobieramy r, g, b obecnego piksela
            rgb = (kolor_piksela.r, kolor_piksela.g, kolor_piksela.b)

            # Jeśli piksel jest w naszej palecie, podmieniamy go!
            if rgb in paleta_rgb:
                new_img.set_at((x, y), paleta_rgb[rgb])

    # Zapisujemy wynik do pliku
    plik_wynikowy = "NAPRAWIONY_" + PLIK_ZRODLOWY
    pygame.image.save(new_img, plik_wynikowy)
    print(f"Zapisano gotowy plik jako: {plik_wynikowy}")

    # ============================================================
    # 4. WYŚWIETLENIE PODGLĄDU NA EKRANIE
    # ============================================================
    font = pygame.font.SysFont("Arial", 24)
    txt_old = font.render("ORYGINAŁ", True, (255, 255, 255))
    txt_new = font.render("PO NAPRAWIE (COLOR_MAP)", True, (255, 255, 255))

    running = True
    while running:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
        
        screen.fill((40, 40, 45))
        
        # Rysujemy oryginał (po lewej) - ze skalowaniem, żebyś lepiej widział
        skala = 3
        img_scaled = pygame.transform.scale(img, (img.get_width() * skala, img.get_height() * skala))
        new_img_scaled = pygame.transform.scale(new_img, (new_img.get_width() * skala, new_img.get_height() * skala))

        screen.blit(txt_old, (50, 50))
        screen.blit(img_scaled, (50, 100))
        
        # Rysujemy naprawiony (po prawej)
        przesuniecie_x = 50 + img_scaled.get_width() + 50
        screen.blit(txt_new, (przesuniecie_x, 50))
        screen.blit(new_img_scaled, (przesuniecie_x, 100))
        
        pygame.display.flip()

    pygame.quit()

if __name__ == "__main__":
    main()